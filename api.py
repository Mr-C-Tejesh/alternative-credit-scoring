def _validate_field_type_and_bounds(
    name: str,
    val: Any,
    bounds: dict[str, Any],
    nullable: bool = False,
) -> float | int | None:
    """Validate numeric type, finiteness, integer constraints, and domain bounds without echoing input values."""
    if val is None:
        if nullable:
            return None
        raise ValueError(f"Field '{name}' is required and cannot be null.")

    if isinstance(val, bool):
        raise ValueError(f"Field '{name}' must be numeric; boolean values are not permitted.")

    if not isinstance(val, (int, float, np.integer, np.floating)):
        raise ValueError(f"Field '{name}' must be a numeric value.")

    float_val = float(val)
    if not np.isfinite(float_val):
        raise ValueError(f"Field '{name}' must be a finite number.")

    if bounds.get("integer_only", False):
        if not float_val.is_integer():
            raise ValueError(f"Field '{name}' must be an integer; fractional values are not permitted.")
        int_val = int(float_val)
        if "allowed_values" in bounds:
            if int_val not in bounds["allowed_values"]:
                allowed = sorted(bounds["allowed_values"])
                raise ValueError(f"Field '{name}' must be one of {allowed}.")
        if "min" in bounds and "max" in bounds:
            if not (bounds["min"] <= int_val <= bounds["max"]):
                raise ValueError(f"Field '{name}' must be in domain bounds [{bounds['min']}, {bounds['max']}].")
        return int_val

    # Float field bounds
    if "min" in bounds and "max" in bounds:
        if not (bounds["min"] <= float_val <= bounds["max"]):
            raise ValueError(f"Field '{name}' must be in domain bounds [{bounds['min']}, {bounds['max']}].")
    return float_val


