class ApplicantPredictRequest(BaseModel):
    """Applicant predictor input payload. Requires all 14 features; extra fields forbidden."""
    model_config = ConfigDict(extra="forbid")

    age_years: Any = Field(
        ...,
        description="Applicant age in years (integer in [20, 65]).",
    )
    monthly_income_inr: Any = Field(
        ...,
        description="Monthly income in Indian Rupees (float in [8000.0, 250000.0]).",
    )
    employment_tenure_years: Any = Field(
        ...,
        description="Employment tenure in years (float in [0.0, 35.0]).",
    )
    debt_to_income_ratio: Any = Field(
        ...,
        description="Debt-to-income ratio (float in [0.0, 1.2]).",
    )
    existing_loan_count: Any = Field(
        ...,
        description="Active existing loan count (integer in [0, 8]).",
    )
    credit_utilization_ratio: Any = Field(
        ...,
        description="Revolving credit card utilization ratio (float in [0.0, 1.25]).",
    )
    prior_delinquencies_24m: Any = Field(
        ...,
        description="Past 24-month delinquency count (integer in [0, 5]).",
    )
    bureau_history_available: Any = Field(
        ...,
        description="Bureau history availability indicator (binary 0 or 1).",
    )
    bureau_score: Any = Field(
        ...,
        description="Credit bureau score (float in [300.0, 900.0], or null if bureau_history_available is 0).",
    )
    utility_payment_timeliness: Any = Field(
        ...,
        description="Utility payment timeliness ratio (float in [0.05, 1.0], or null if unavailable).",
    )
    rental_payment_timeliness: Any = Field(
        ...,
        description="Rental payment timeliness ratio (float in [0.05, 1.0], or null if unavailable).",
    )
    digital_payment_regularity: Any = Field(
        ...,
        description="Digital payment regularity index (float in [0.02, 1.0], or null if unavailable).",
    )
    cashflow_stability_index: Any = Field(
        ...,
        description="Cash-flow stability index (float in [0.02, 1.0], or null if unavailable).",
    )
    alternative_history_months: Any = Field(
        ...,
        description="Alternative history length in months (integer in [0, 24], or null if unavailable).",
    )

    @field_validator(
        "age_years",
        "monthly_income_inr",
        "employment_tenure_years",
        "debt_to_income_ratio",
        "existing_loan_count",
        "credit_utilization_ratio",
        "prior_delinquencies_24m",
        "bureau_history_available",
        "bureau_score",
        "utility_payment_timeliness",
        "rental_payment_timeliness",
        "digital_payment_regularity",
        "cashflow_stability_index",
        "alternative_history_months",
        mode="before",
    )
    @classmethod
    def validate_individual_field(cls, val: Any, info: ValidationInfo) -> Any:
        field_name = info.field_name
        bounds = DOMAIN_BOUNDS[field_name]
        nullable = field_name in _PERMITTED_MISSING_INFERENCE
        return _validate_field_type_and_bounds(field_name, val, bounds, nullable=nullable)

    @model_validator(mode="after")
    def validate_bureau_consistency(self) -> "ApplicantPredictRequest":
        hist_avail = self.bureau_history_available
        b_score = self.bureau_score

        if hist_avail == 0:
            if b_score is not None:
                raise ValueError("Field 'bureau_score' must be null when 'bureau_history_available' is 0.")
        elif hist_avail == 1:
            if b_score is None:
                raise ValueError("Field 'bureau_score' must not be null when 'bureau_history_available' is 1.")
        return self

    def to_feature_dataframe(self) -> pd.DataFrame:
        """Convert validated request payload into a single-row DataFrame aligned with ALL_FEATURES."""
        data = self.model_dump()
        row_dict = {}
        for col in ALL_FEATURES:
            val = data[col]
            row_dict[col] = np.nan if val is None else val
        return pd.DataFrame([row_dict], columns=ALL_FEATURES)


