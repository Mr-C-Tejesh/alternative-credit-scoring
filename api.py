def create_app(
    model_path: Path | str | None = None,
    manifest_path: Path | str | None = None,
    model: Pipeline | None = None,
    load_on_startup: bool = True,
    model_loader: Callable[..., Pipeline] | None = None,
    metrics_registry: CollectorRegistry | None = None,
    enforce_integrity: bool = True,
) -> FastAPI:
    """Create and configure the FastAPI application instance."""

    # Isolated metrics registry per application instance (prevents cross-test pollution)
    metrics = APIMetrics(registry=metrics_registry)

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        if app.state.model is None and load_on_startup:
            loader = app.state.model_loader or load_saved_model
            target_path = getattr(app.state, "model_path", None) or DEFAULT_MODEL_PATH
            target_manifest = getattr(app.state, "manifest_path", None) or DEFAULT_MANIFEST_PATH
            try:
                logger.info("Initializing inference model from configured artifact...")
                if getattr(app.state, "enforce_integrity", True):
                    manifest = verify_model_artifact_integrity(
                        model_path=target_path,
                        manifest_path=target_manifest,
                    )
                    logger.info(
                        "Model artifact integrity verified (SHA-256: %s..., model: %s).",
                        manifest["sha256"][:8],
                        manifest.get("model_identifier", "unknown"),
                    )
                loaded = loader(target_path)
                app.state.model = loaded
                app.state.is_ready = True
                app.state.metrics.model_ready.labels(model=MODEL_IDENTIFIER).set(1)
                logger.info("Model loaded successfully into service state.")
            except Exception as err:
                logger.error("Failed to load model artifact or verify integrity: %s", type(err).__name__)
                app.state.model = None
                app.state.is_ready = False
                app.state.metrics.model_ready.labels(model=MODEL_IDENTIFIER).set(0)
        yield

    app = FastAPI(
        title="Alternative Credit Scoring Inference API",
        description=(
            "Educational demonstration HTTP inference service for synthetic alternative credit scoring. "
            "Exposes the trained Hybrid Logistic Regression pipeline for probabilistic predictions, "
            "illustrative score scaling (PDO), risk band mapping, and exact additive log-odds feature explanations. "
            "Strictly simulated for machine learning engineering and observability demonstration; "
            "not validated for real borrowers or credit decisions."
        ),
        version="1.0.0",
        lifespan=lifespan,
    )

    # State initialization
    app.state.model_path = Path(model_path) if model_path is not None else None
    app.state.manifest_path = Path(manifest_path) if manifest_path is not None else None
    app.state.model = model
    app.state.is_ready = model is not None
    app.state.model_loader = model_loader
    app.state.enforce_integrity = enforce_integrity
    app.state.metrics = metrics
    app.state.metrics_registry = metrics.registry

    # Initialize model_ready gauge based on initial model presence
    app.state.metrics.model_ready.labels(model=MODEL_IDENTIFIER).set(1 if model is not None else 0)

    # Safe metrics middleware: uses bounded route labels and excludes /metrics scrapes
    @app.middleware("http")
    async def metrics_middleware(request: Request, call_next):
        # Exclude /metrics scrapes from request metrics to prevent self-observation loops
        if request.url.path == "/metrics":
            return await call_next(request)

        raw_path = request.url.path
        route_label = raw_path if raw_path in KNOWN_METRIC_ROUTES else "unmatched"
        method_label = request.method if request.method in VALID_HTTP_METHODS else "OTHER"

        start_time = time.perf_counter()
        status_code = "500"
        try:
            response = await call_next(request)
            status_code = str(response.status_code)
            return response
        except Exception:
            status_code = "500"
            raise
        finally:
            duration = max(0.0, time.perf_counter() - start_time)
            app_metrics: APIMetrics = app.state.metrics
            app_metrics.http_requests_total.labels(
                route=route_label,
                method=method_label,
                status=status_code,
            ).inc()
            app_metrics.http_request_duration_seconds.labels(
                route=route_label,
                method=method_label,
            ).observe(duration)

    # Safe validation exception handler: strips raw user input values
    @app.exception_handler(RequestValidationError)
    async def validation_exception_handler(request: Request, exc: RequestValidationError):
        if request.url.path == "/v1/predict":
            app.state.metrics.prediction_outcomes_total.labels(
                model=MODEL_IDENTIFIER, outcome="validation_error"
            ).inc()

        sanitized_errors = []
        for err in exc.errors():
            loc = err.get("loc", ())
            field_name = loc[-1] if loc else "request"
            msg = err.get("msg", "Validation error.")
            if msg.startswith("Value error, "):
                msg = msg[len("Value error, "):]
            sanitized_errors.append({
                "field": str(field_name),
                "message": msg,
                "type": err.get("type", "validation_error"),
            })
        return JSONResponse(
            status_code=422,
            content={
                "detail": sanitized_errors,
                "errors": sanitized_errors,
            },
        )

    # 1. Liveness check: confirms process is alive, does NOT claim model readiness
    @app.get("/health", response_model=HealthResponse, tags=["Observability"])
    async def health_check() -> HealthResponse:
        return HealthResponse(status="healthy", service="alternative-credit-scoring-api")

    # 2. Readiness check: confirms model is loaded and ready
    @app.get("/ready", response_model=ReadyResponse, tags=["Observability"])
    async def readiness_check(response: Response) -> ReadyResponse:
        if app.state.model is not None and getattr(app.state, "is_ready", False):
            app.state.metrics.model_ready.labels(model=MODEL_IDENTIFIER).set(1)
            return ReadyResponse(
                status="ready",
                model_loaded=True,
                model_identifier=MODEL_IDENTIFIER,
                message="Service is ready for inference.",
            )
        response.status_code = status.HTTP_503_SERVICE_UNAVAILABLE
        app.state.metrics.model_ready.labels(model=MODEL_IDENTIFIER).set(0)
        return ReadyResponse(
            status="unready",
            model_loaded=False,
            model_identifier=None,
            message="Model artifact is not loaded or unavailable.",
        )

    # 3. Prediction endpoint
    @app.post(
        "/v1/predict",
        response_model=PredictResponse,
        status_code=status.HTTP_200_OK,
        tags=["Inference"],
        summary="Predict 12-month default probability with illustrative score and explanations",
    )
    async def predict_endpoint(payload: ApplicantPredictRequest) -> PredictResponse:
        # Check service readiness
        if app.state.model is None or not getattr(app.state, "is_ready", False):
            app.state.metrics.prediction_outcomes_total.labels(
                model=MODEL_IDENTIFIER, outcome="service_unready"
            ).inc()
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Model service is not ready to process predictions.",
            )

        try:
            applicant_df = payload.to_feature_dataframe()
            inference_res: InferenceResult = run_inference_pipeline(
                model=app.state.model,
                row=applicant_df,
                validate=True,
                top_k_explanations=3,
            )
        except HTTPException:
            app.state.metrics.prediction_outcomes_total.labels(
                model=MODEL_IDENTIFIER, outcome="internal_error"
            ).inc()
            raise
        except Exception as err:
            app.state.metrics.prediction_outcomes_total.labels(
                model=MODEL_IDENTIFIER, outcome="internal_error"
            ).inc()
            logger.error("Inference execution failed: %s", type(err).__name__)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="An internal error occurred during prediction.",
            )

        # Validate prediction output contract
        prob = float(inference_res.probability)
        if not np.isfinite(prob) or not (0.0 <= prob <= 1.0):
            app.state.metrics.prediction_outcomes_total.labels(
                model=MODEL_IDENTIFIER, outcome="internal_error"
            ).inc()
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Model produced an invalid probability value.",
            )

        app.state.metrics.prediction_outcomes_total.labels(
            model=MODEL_IDENTIFIER, outcome="success"
        ).inc()

        top_increasing = [
            FeatureContributionItem(
                feature=str(item["feature"]),
                readable_name=str(item["readable_name"]),
                transformed_value=float(item["transformed_value"]),
                coefficient=float(item["coefficient"]),
                contribution=float(item["contribution"]),
            )
            for item in inference_res.explanation.top_risk_increasing
        ]

        top_decreasing = [
            FeatureContributionItem(
                feature=str(item["feature"]),
                readable_name=str(item["readable_name"]),
                transformed_value=float(item["transformed_value"]),
                coefficient=float(item["coefficient"]),
                contribution=float(item["contribution"]),
            )
            for item in inference_res.explanation.top_risk_decreasing
        ]

        scoring_meta = ScoringMetadata(
            display_score=int(inference_res.score_result.display_score),
            raw_score=float(inference_res.score_result.raw_score),
            is_clamped=bool(inference_res.score_result.is_clamped),
            min_score=int(inference_res.score_result.min_score),
            max_score=int(inference_res.score_result.max_score),
            base_score=float(inference_res.score_result.base_score),
            base_odds=float(inference_res.score_result.base_odds),
            pdo=float(inference_res.score_result.pdo),
        )

        return PredictResponse(
            model_identifier=MODEL_IDENTIFIER,
            schema_version=SCHEMA_VERSION,
            default_probability_12m=prob,
            risk_band=str(inference_res.risk_band),
            scoring=scoring_meta,
            top_risk_increasing_factors=top_increasing,
            top_risk_decreasing_factors=top_decreasing,
            disclaimer=DISCLAIMER_TEXT,
            educational_notice=EDUCATIONAL_NOTICE_TEXT,
        )

    # 4. Observability metrics endpoint: Prometheus text exposition
    @app.get(
        "/metrics",
        tags=["Observability"],
        summary="Expose operational Prometheus metrics",
        response_class=Response,
    )
    async def metrics_endpoint() -> Response:
        is_ready = 1 if getattr(app.state, "is_ready", False) else 0
        app.state.metrics.model_ready.labels(model=MODEL_IDENTIFIER).set(is_ready)

        data = generate_latest(app.state.metrics.registry)
        return Response(
            content=data,
            media_type=CONTENT_TYPE_LATEST,
        )

    return app


# Default application instance for Uvicorn entrypoint
app = create_app()


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("api:app", host="127.0.0.1", port=8000, reload=False)
